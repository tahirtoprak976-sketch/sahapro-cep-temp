await assert.rejects(linkPdfWork(db,{...row,quantity:3},'FILE','DOC','W',{confirmed:true}));
await linkPdfWork(db,{...row,unit_price:100,kdv_rate:null,kdv_included:null},'FILE','DOC','W',{confirmed:true});

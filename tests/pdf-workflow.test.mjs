const fuel={...row,kind:'fuel',fuel_source:'',liters:210,customer_id:''};
assert.equal(pdfQuestions(fuel,d)[0].key,'fuel_source');
answerPdfQuestion(fuel,'fuel_source','Müşteri Verdi',d);assert.equal(pdfQuestions(fuel,d)[0].key,'customer_id');
assert.throws(()=>answerPdfQuestion(fuel,'customer_id','unknown',d));
answerPdfQuestion(fuel,'customer_id','C',d);assert.equal(pdfQuestions(fuel,d).length,0);
const q={...row,date:'2026-02-31'};assert.throws(()=>answerPdfQuestion(q,'date','2026-02-31',d));answerPdfQuestion(q,'date','2026-02-28',d);
const price={...row,unit_price:100,kdv_rate:null,kdv_included:null};answerPdfQuestion(price,'kdv_rate',0,d);answerPdfQuestion(price,'kdv_included',false,d);assert.equal(pdfQuestions(price,d).length,0);
const existing={id:'W',date:row.date,vehicle_id:'V',customer_id:'C',unit:'Saat',quantity:2,work_type:'Kazı',price_snapshot:{amount:3000,locked:true}};
let called=0;
const db={dumpAll:async()=>({...d,work_records:[existing]}),opHash:async()=> 'HASH',linkPdfWorkSource:async request=>{called++;assert.equal(request.recordId,'W');assert.equal(request.source.page,1);return existing;}};
await assert.rejects(linkPdfWork(db,row,'FILE','DOC','W'));

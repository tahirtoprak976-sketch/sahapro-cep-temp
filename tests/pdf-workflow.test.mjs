import assert from 'node:assert/strict';
import {pdfMappingTargets,applyPdfMapping,pdfQuestions,answerPdfQuestion,linkPdfWork} from '../js/pdf-history-core.js';
const d={customers:[{id:'C',name:'Örnek'}],vehicles:[{id:'V',name:'Test'}],personnel:[{id:'P',name:'Soner'}]};
const row={id:'0',kind:'work',page:1,quote:'Kaynak',date:'2026-05-11',customer_id:'C',vehicle_id:'V',personnel_name:'Soner Abi',personnel_id:'P',work_type:'Kazı',unit:'Saat',quantity:2,unit_price:null};
const plan={rows:[row,{...row,id:'1',personnel_id:''},{...row,id:'2',personnel_id:'OTHER'},{...row,id:'3',personnel_id:''},{...row,id:'4',personnel_name:'Soner Usta',personnel_id:''}]};
const completed=new Set(['3']);
assert.deepEqual(pdfMappingTargets(plan,'personnel_id','Soner Abi','P',d,completed),['1']);
assert.deepEqual(applyPdfMapping(plan,'personnel_id','Soner Abi','P',d,completed),['1']);
assert.equal(plan.rows[2].personnel_id,'OTHER');assert.equal(plan.rows[3].personnel_id,'');assert.equal(plan.rows[4].personnel_id,'');
